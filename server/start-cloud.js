// 云端模式启动入口（部署时使用：startCmd = "npm run start:cloud"）
//
// 为什么要单独一个入口：云端模式的开关是环境变量 TIDY_CLOUD=1，而发布时的启动命令
// 有被重新探测的风险（历史上就因为重新发布丢了变量，线上静默退回本地单机模式，
// 表现为没有登录页、顶栏没有空间切换胶囊、侧边栏没有「实验室」）。
// 把变量写在代码里，就不再依赖 shell 是否支持 `VAR=1 cmd` 这种前缀写法，跨平台一致。
//
// 本地开发请继续用 `npm start`（不带云端开关，跑本机 SQLite，行为与单机版完全一致）。
process.env.TIDY_CLOUD = '1';
require('./index.js');
